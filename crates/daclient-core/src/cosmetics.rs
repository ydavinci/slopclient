//! Capes made in the launcher's Cape Studio: the shared format and the local library.
//!
//! Format (shared by launcher, client mod and later the backend):
//! - `cape.png`: all frames stacked vertically, each in Minecraft's 64 × 32 cape
//!   layout times `scale` (1, 2, 4 or 8).
//! - `cape.json`: [`CapeMeta`].
//!
//! Library: `cosmetics/capes/<id>/` with `cape.png`, `cape.json`, `info.json`
//! (name, editor state) and optionally `source.<ext>` (the original upload, local only).

use std::path::PathBuf;

use image::{ImageFormat, ImageReader};
use serde::{Deserialize, Serialize};

use crate::{Error, Paths, Result, config::Settings, instance::now};

pub const BASE_WIDTH: u32 = 64;
pub const BASE_HEIGHT: u32 = 32;
pub const SCALES: [u32; 4] = [1, 2, 4, 8];
pub const MAX_FRAMES: u32 = 64;
pub const MIN_FRAME_MS: u32 = 40;
pub const MAX_BYTES: usize = 2 * 1024 * 1024;
const SOURCE_EXTS: [&str; 5] = ["gif", "png", "webp", "jpg", "jpeg"];

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct CapeMeta {
    pub version: u32,
    pub frames: u32,
    pub frame_time_ms: u32,
    pub scale: u32,
    /// Also show the cape on elytra.
    pub elytra: bool,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct CapeInfo {
    pub id: String,
    pub name: String,
    pub meta: CapeMeta,
    pub created_at: u64,
    pub updated_at: u64,
    /// Original upload exists, so the cape can be edited again.
    #[serde(default)]
    pub has_source: bool,
}

#[derive(Debug, Default, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
struct InfoFile {
    name: String,
    created_at: u64,
    updated_at: u64,
    #[serde(default)]
    editor: serde_json::Value,
}

/// Checks the meta data against the limits.
pub fn check_meta(meta: &CapeMeta) -> Result<()> {
    let bad = |m: String| Err(Error::Other(m));
    if meta.version != 1 {
        return bad(format!("unsupported cape format version {}", meta.version));
    }
    if !SCALES.contains(&meta.scale) {
        return bad(format!("scale must be one of {SCALES:?}"));
    }
    if meta.frames == 0 || meta.frames > MAX_FRAMES {
        return bad(format!("a cape has 1 to {MAX_FRAMES} frames"));
    }
    if meta.frames > 1 && meta.frame_time_ms < MIN_FRAME_MS {
        return bad(format!("frames must show at least {MIN_FRAME_MS} ms"));
    }
    Ok(())
}

/// Validates a spritesheet against its meta data and re-encodes it, so nothing but
/// the pixels is ever stored or shared.
pub fn validate(png: &[u8], meta: &CapeMeta) -> Result<Vec<u8>> {
    check_meta(meta)?;
    if png.len() > MAX_BYTES {
        return Err(Error::Other(format!("the cape is larger than {} MB", MAX_BYTES / 1024 / 1024)));
    }
    let img = ImageReader::with_format(std::io::Cursor::new(png), ImageFormat::Png)
        .decode()
        .map_err(|e| Error::Other(format!("the cape is not a valid PNG: {e}")))?;
    let (w, h) = (BASE_WIDTH * meta.scale, BASE_HEIGHT * meta.scale * meta.frames);
    if img.width() != w || img.height() != h {
        return Err(Error::Other(format!(
            "expected a {w} × {h} spritesheet for {} frames at scale {}, got {} × {}",
            meta.frames,
            meta.scale,
            img.width(),
            img.height()
        )));
    }
    let mut out = std::io::Cursor::new(Vec::new());
    img.to_rgba8()
        .write_to(&mut out, ImageFormat::Png)
        .map_err(|e| Error::Other(format!("could not encode the cape: {e}")))?;
    let out = out.into_inner();
    if out.len() > MAX_BYTES {
        return Err(Error::Other(format!("the cape is larger than {} MB", MAX_BYTES / 1024 / 1024)));
    }
    Ok(out)
}

fn root(paths: &Paths) -> PathBuf {
    paths.root.join("cosmetics").join("capes")
}

fn dir(paths: &Paths, id: &str) -> Result<PathBuf> {
    // Ids are generated by us; anything else is refused before touching the disk.
    if id.is_empty() || !id.chars().all(|c| c.is_ascii_alphanumeric() || c == '-') {
        return Err(Error::Other(format!("invalid cape id: {id}")));
    }
    Ok(root(paths).join(id))
}

fn source_file(dir: &std::path::Path) -> Option<PathBuf> {
    SOURCE_EXTS.iter().map(|e| dir.join(format!("source.{e}"))).find(|p| p.is_file())
}

fn read_info(paths: &Paths, id: &str) -> Result<CapeInfo> {
    let d = dir(paths, id)?;
    let meta: CapeMeta = serde_json::from_str(&std::fs::read_to_string(d.join("cape.json"))?)?;
    let info: InfoFile = std::fs::read_to_string(d.join("info.json"))
        .ok()
        .and_then(|t| serde_json::from_str(&t).ok())
        .unwrap_or_default();
    Ok(CapeInfo {
        id: id.to_owned(),
        name: if info.name.is_empty() { "Cape".into() } else { info.name },
        meta,
        created_at: info.created_at,
        updated_at: info.updated_at,
        has_source: source_file(&d).is_some(),
    })
}

/// All capes, newest first.
pub fn list(paths: &Paths) -> Result<Vec<CapeInfo>> {
    let Ok(entries) = std::fs::read_dir(root(paths)) else {
        return Ok(Vec::new());
    };
    let mut capes: Vec<CapeInfo> = entries
        .flatten()
        .filter_map(|e| read_info(paths, &e.file_name().to_string_lossy()).ok())
        .collect();
    capes.sort_by(|a, b| b.updated_at.cmp(&a.updated_at));
    Ok(capes)
}

/// What the Cape Studio hands over when saving.
pub struct NewCape<'a> {
    /// Existing id to overwrite, or `None` for a new cape.
    pub id: Option<&'a str>,
    pub name: &'a str,
    pub png: &'a [u8],
    pub meta: CapeMeta,
    /// Original upload (`ext`, bytes) so the cape can be edited later.
    pub source: Option<(&'a str, &'a [u8])>,
    /// Editor settings (crop, colours, trim), stored as-is for re-editing.
    pub editor: serde_json::Value,
}

pub fn save(paths: &Paths, cape: NewCape<'_>) -> Result<CapeInfo> {
    let png = validate(cape.png, &cape.meta)?;
    let id = match cape.id {
        Some(id) => id.to_owned(),
        None => format!("{:x}-{:04x}", now(), rand_suffix()),
    };
    let d = dir(paths, &id)?;
    std::fs::create_dir_all(&d)?;
    std::fs::write(d.join("cape.png"), png)?;
    std::fs::write(d.join("cape.json"), serde_json::to_string_pretty(&cape.meta)?)?;

    let previous: Option<InfoFile> = std::fs::read_to_string(d.join("info.json"))
        .ok()
        .and_then(|t| serde_json::from_str(&t).ok());
    let created_at = previous.as_ref().map_or_else(now, |p| p.created_at);
    let name = cape.name.trim();
    let info = InfoFile {
        name: if name.is_empty() { "Cape".into() } else { name.chars().take(40).collect() },
        created_at,
        updated_at: now(),
        editor: cape.editor,
    };
    std::fs::write(d.join("info.json"), serde_json::to_string_pretty(&info)?)?;

    if let Some((ext, bytes)) = cape.source {
        let ext = ext.trim_start_matches('.').to_ascii_lowercase();
        if !SOURCE_EXTS.contains(&ext.as_str()) {
            return Err(Error::Other(format!("unsupported source format: {ext}")));
        }
        if bytes.len() > 32 * 1024 * 1024 {
            return Err(Error::Other("the original file is larger than 32 MB".into()));
        }
        if let Some(old) = source_file(&d) {
            std::fs::remove_file(old)?;
        }
        std::fs::write(d.join(format!("source.{ext}")), bytes)?;
    }
    read_info(paths, &id)
}

fn rand_suffix() -> u32 {
    // Unique enough within one second on one machine; ids are local.
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.subsec_nanos() & 0xffff)
        .unwrap_or(0)
}

pub fn delete(paths: &Paths, id: &str) -> Result<()> {
    let d = dir(paths, id)?;
    if d.is_dir() {
        std::fs::remove_dir_all(d)?;
    }
    let mut settings = Settings::load(paths)?;
    if settings.active_cape.as_deref() == Some(id) {
        settings.active_cape = None;
        settings.save(paths)?;
    }
    Ok(())
}

pub fn cape_png(paths: &Paths, id: &str) -> Result<Vec<u8>> {
    Ok(std::fs::read(dir(paths, id)?.join("cape.png"))?)
}

/// Original upload and editor state, for editing a cape again.
pub fn source(paths: &Paths, id: &str) -> Result<Option<(String, Vec<u8>, serde_json::Value)>> {
    let d = dir(paths, id)?;
    let Some(file) = source_file(&d) else {
        return Ok(None);
    };
    let ext = file.extension().unwrap_or_default().to_string_lossy().into_owned();
    let editor = std::fs::read_to_string(d.join("info.json"))
        .ok()
        .and_then(|t| serde_json::from_str::<InfoFile>(&t).ok())
        .map(|i| i.editor)
        .unwrap_or_default();
    Ok(Some((ext, std::fs::read(file)?, editor)))
}

pub fn active(paths: &Paths) -> Result<Option<CapeInfo>> {
    let Some(id) = Settings::load(paths)?.active_cape else {
        return Ok(None);
    };
    Ok(read_info(paths, &id).ok())
}

pub fn set_active(paths: &Paths, id: Option<&str>) -> Result<()> {
    if let Some(id) = id {
        read_info(paths, id)?;
    }
    let mut settings = Settings::load(paths)?;
    settings.active_cape = id.map(str::to_owned);
    settings.save(paths)
}

#[cfg(test)]
mod tests {
    use super::*;
    use image::RgbaImage;

    fn sheet(scale: u32, frames: u32) -> Vec<u8> {
        let img = RgbaImage::new(BASE_WIDTH * scale, BASE_HEIGHT * scale * frames);
        let mut out = std::io::Cursor::new(Vec::new());
        img.write_to(&mut out, ImageFormat::Png).unwrap();
        out.into_inner()
    }

    fn meta(scale: u32, frames: u32, ms: u32) -> CapeMeta {
        CapeMeta { version: 1, frames, frame_time_ms: ms, scale, elytra: true }
    }

    #[test]
    fn accepts_matching_spritesheets() {
        assert!(validate(&sheet(1, 1), &meta(1, 1, 0)).is_ok());
        assert!(validate(&sheet(4, 12), &meta(4, 12, 80)).is_ok());
    }

    #[test]
    fn rejects_wrong_dimensions_and_limits() {
        assert!(validate(&sheet(2, 3), &meta(2, 4, 80)).is_err());
        assert!(validate(&sheet(3, 1), &meta(3, 1, 0)).is_err());
        assert!(check_meta(&meta(1, 65, 80)).is_err());
        assert!(check_meta(&meta(1, 10, 20)).is_err());
        assert!(validate(b"no png", &meta(1, 1, 0)).is_err());
    }

    #[test]
    fn library_round_trip() {
        let root = std::env::temp_dir().join(format!("daclient-capes-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        let paths = Paths::new(&root);
        let info = save(
            &paths,
            NewCape {
                id: None,
                name: "Galaxie",
                png: &sheet(2, 4),
                meta: meta(2, 4, 100),
                source: Some(("gif", b"GIF89a")),
                editor: serde_json::json!({ "zoom": 1.5 }),
            },
        )
        .unwrap();
        assert_eq!(list(&paths).unwrap().len(), 1);
        assert!(info.has_source);
        set_active(&paths, Some(&info.id)).unwrap();
        assert_eq!(active(&paths).unwrap().unwrap().name, "Galaxie");
        let (ext, bytes, editor) = source(&paths, &info.id).unwrap().unwrap();
        assert_eq!((ext.as_str(), bytes.as_slice(), editor["zoom"].as_f64()), ("gif", &b"GIF89a"[..], Some(1.5)));
        delete(&paths, &info.id).unwrap();
        assert!(list(&paths).unwrap().is_empty());
        assert!(active(&paths).unwrap().is_none());
        assert!(dir(&paths, "../evil").is_err());
        let _ = std::fs::remove_dir_all(&root);
    }
}
